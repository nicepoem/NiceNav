type SeedSite = {
  id: string
  title: string
  url: string
  description?: string
  tags?: string[]
}

function makeSites(categoryId: string, items: SeedSite[], ts: number): Site[] {
  return items.map((item, order) => ({
    id: item.id,
    categoryId,
    title: item.title,
    url: item.url,
    description: item.description ?? '',
    order,
    tags: item.tags ?? [],
    createdAt: ts,
    updatedAt: ts,
  }))
}

function makeCategory(
  id: string,
  name: string,
  icon: string,
  order: number,
  ts: number,
  parentId: string | null = null,
): Category {
  return { id, name, icon, parentId, order, createdAt: ts, updatedAt: ts }
}

